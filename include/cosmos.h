/* The Cosmos SDK: serverless 2-4 player sessions, C API.
 *
 * Model: poll-based. The library runs its own threads internally but never
 * calls back into your code. Call cosmos_poll() (e.g. once per frame, until
 * it returns 0) to receive events one at a time.
 *
 * Lifetimes: pointers inside a cosmos_event_t (data, message, record_kind,
 * record_key, publisher) stay valid until the next cosmos_poll() or
 * cosmos_shutdown() on the same handle. Copy what you need to keep.
 *
 * Threads: every call is safe from any thread. cosmos_host() and
 * cosmos_join() block (DHT publish / lookup and handshake, up to ~30 s);
 * call them from a worker thread if the game must keep rendering.
 * cosmos_shutdown() frees the handle: no other call on it may run at the
 * same time or after.
 *
 * Sessions: one per handle. After it ends (or a join fails past the code
 * lookup), create a new handle for the next one.
 *
 * Errors: calls return COSMOS_OK (0) or a negative COSMOS_E_* code;
 * cosmos_error_name() names it and cosmos_last_error() describes the last
 * failure on the calling thread. A panic inside the library is caught and
 * returned as COSMOS_E_PANIC.
 */


